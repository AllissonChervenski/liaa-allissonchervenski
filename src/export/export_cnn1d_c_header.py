#!/usr/bin/env python3
"""Export Quantized INT8 1D-CNN Weights, Scales, and Offsets to Static C99 Header.

Generates `embedded/firmware/include/cnn1d_weights_int8.h` (and a copy in
`embedded/firmware/src/cnn1d_weights_int8.h`) from `reports/cnn1d_qemu/cnn1d_model_artifacts.npz`.

All tensors are emitted as `static const int8_t` / `static const int32_t` / `static const float`
with zero compiler warnings under `xtensa-esp32s3-elf-gcc -Wall -Wextra -Werror`.
"""
from __future__ import annotations

import argparse
from pathlib import Path
import numpy as np

ROOT = Path(__file__).resolve().parents[2]


def format_int_array(name: str, ctype: str, arr: np.ndarray, cols: int = 16) -> str:
    flat = arr.ravel().tolist()
    lines = [f"static const {ctype} {name}[{len(flat)}] = {{"]
    for i in range(0, len(flat), cols):
        chunk = ", ".join(str(int(v)) for v in flat[i : i + cols])
        suffix = "," if (i + cols) < len(flat) else ""
        lines.append(f"    {chunk}{suffix}")
    lines.append("};")
    return "\n".join(lines)


def format_float_array(name: str, arr: np.ndarray, cols: int = 8) -> str:
    flat = arr.ravel().tolist()
    lines = [f"static const float {name}[{len(flat)}] = {{"]
    for i in range(0, len(flat), cols):
        chunk = ", ".join(f"{float(v):.9e}f" for v in flat[i : i + cols])
        suffix = "," if (i + cols) < len(flat) else ""
        lines.append(f"    {chunk}{suffix}")
    lines.append("};")
    return "\n".join(lines)


def generate_c_header(npz_path: Path, out_headers: list[Path]) -> None:
    data = np.load(npz_path)

    chunks: list[str] = [
        "/*",
        " * cnn1d_weights_int8.h — Auto-generated Static INT8 Weights & Quantization Scales",
        " *",
        " * Generated by: src/export/export_cnn1d_c_header.py",
        " * Source artifacts: reports/cnn1d_qemu/cnn1d_model_artifacts.npz",
        " * Quantization scheme: Symmetric INT8 weights & activations, zero-point = 0",
        " */",
        "",
        "#ifndef CNN1D_WEIGHTS_INT8_H",
        "#define CNN1D_WEIGHTS_INT8_H",
        "",
        "#include <stdint.h>",
        '#include "cnn1d_inference.h"',
        "",
        "/* ==========================================================================",
        " * 1. PRIMARY DATASET: OZDEMIR ET AL. (4 CHANNELS, 10 CLASSES, 2,906 PARAMS)",
        " * ========================================================================== */",
        f"#define OZDEMIR_IN_QUANT_SCALE  ({float(data['oz_in_quant_scale'][0]):.9e}f)",
        f"#define OZDEMIR_AUX_QUANT_SCALE ({float(data['oz_aux_quant_scale'][0]):.9e}f)",
        f"#define OZDEMIR_CONV1_EFF_SCALE ({float(data['oz_conv1_s'][0]):.9e}f)",
        f"#define OZDEMIR_CONV2_EFF_SCALE ({float(data['oz_conv2_s'][0]):.9e}f)",
        f"#define OZDEMIR_FC_EFF_SCALE    ({float(data['oz_fc_s'][0]):.9e}f)",
        f"#define OZDEMIR_AUX_EFF_SCALE   ({float(data['oz_aux_s'][0]):.9e}f)",
        "#define OZDEMIR_ZERO_POINT      (0)",
        "",
        format_float_array("g_ozdemir_in_mean", data["oz_in_mean"]),
        format_float_array("g_ozdemir_in_inv_std", data["oz_in_inv_std"]),
        format_float_array("g_ozdemir_aux_mean", data["oz_aux_mean"]),
        format_float_array("g_ozdemir_aux_inv_std", data["oz_aux_inv_std"]),
        format_int_array("g_ozdemir_conv1_weights", "int8_t", data["oz_conv1_w"]),
        format_int_array("g_ozdemir_conv1_bias", "int32_t", data["oz_conv1_b"]),
        format_int_array("g_ozdemir_conv2_weights", "int8_t", data["oz_conv2_w"]),
        format_int_array("g_ozdemir_conv2_bias", "int32_t", data["oz_conv2_b"]),
        format_int_array("g_ozdemir_fc_weights", "int8_t", data["oz_fc_w"]),
        format_int_array("g_ozdemir_fc_bias", "int32_t", data["oz_fc_b"]),
        format_int_array("g_ozdemir_aux_fc_weights", "int8_t", data["oz_aux_w"]),
        "",
        "static const cnn1d_model_config_t g_cnn1d_ozdemir_config = {",
        "    .in_channels      = 4,",
        "    .num_classes      = 10,",
        "    .in_mean          = g_ozdemir_in_mean,",
        "    .in_inv_std       = g_ozdemir_in_inv_std,",
        "    .in_quant_scale   = OZDEMIR_IN_QUANT_SCALE,",
        "    .conv1_weights    = g_ozdemir_conv1_weights,",
        "    .conv1_bias       = g_ozdemir_conv1_bias,",
        "    .conv1_eff_scale  = OZDEMIR_CONV1_EFF_SCALE,",
        "    .conv2_weights    = g_ozdemir_conv2_weights,",
        "    .conv2_bias       = g_ozdemir_conv2_bias,",
        "    .conv2_eff_scale  = OZDEMIR_CONV2_EFF_SCALE,",
        "    .fc_weights       = g_ozdemir_fc_weights,",
        "    .fc_bias          = g_ozdemir_fc_bias,",
        "    .fc_eff_scale     = OZDEMIR_FC_EFF_SCALE,",
        "    .num_aux_features = 20,",
        "    .aux_mean         = g_ozdemir_aux_mean,",
        "    .aux_inv_std      = g_ozdemir_aux_inv_std,",
        "    .aux_quant_scale  = OZDEMIR_AUX_QUANT_SCALE,",
        "    .aux_fc_weights   = g_ozdemir_aux_fc_weights,",
        "    .aux_fc_eff_scale = OZDEMIR_AUX_EFF_SCALE",
        "};",
        "",
        "/* ==========================================================================",
        " * 2. SECONDARY DATASET: NINAPRO DB2 (12 CHANNELS, 50 CLASSES, 7,562 PARAMS)",
        " * ========================================================================== */",
        f"#define NINAPRO_IN_QUANT_SCALE  ({float(data['ni_in_quant_scale'][0]):.9e}f)",
        f"#define NINAPRO_AUX_QUANT_SCALE ({float(data['ni_aux_quant_scale'][0]):.9e}f)",
        f"#define NINAPRO_CONV1_EFF_SCALE ({float(data['ni_conv1_s'][0]):.9e}f)",
        f"#define NINAPRO_CONV2_EFF_SCALE ({float(data['ni_conv2_s'][0]):.9e}f)",
        f"#define NINAPRO_FC_EFF_SCALE    ({float(data['ni_fc_s'][0]):.9e}f)",
        f"#define NINAPRO_AUX_EFF_SCALE   ({float(data['ni_aux_s'][0]):.9e}f)",
        "#define NINAPRO_ZERO_POINT      (0)",
        "",
        format_float_array("g_ninapro_in_mean", data["ni_in_mean"]),
        format_float_array("g_ninapro_in_inv_std", data["ni_in_inv_std"]),
        format_float_array("g_ninapro_aux_mean", data["ni_aux_mean"]),
        format_float_array("g_ninapro_aux_inv_std", data["ni_aux_inv_std"]),
        format_int_array("g_ninapro_conv1_weights", "int8_t", data["ni_conv1_w"]),
        format_int_array("g_ninapro_conv1_bias", "int32_t", data["ni_conv1_b"]),
        format_int_array("g_ninapro_conv2_weights", "int8_t", data["ni_conv2_w"]),
        format_int_array("g_ninapro_conv2_bias", "int32_t", data["ni_conv2_b"]),
        format_int_array("g_ninapro_fc_weights", "int8_t", data["ni_fc_w"]),
        format_int_array("g_ninapro_fc_bias", "int32_t", data["ni_fc_b"]),
        format_int_array("g_ninapro_aux_fc_weights", "int8_t", data["ni_aux_w"]),
        "",
        "static const cnn1d_model_config_t g_cnn1d_ninapro_config = {",
        "    .in_channels      = 12,",
        "    .num_classes      = 50,",
        "    .in_mean          = g_ninapro_in_mean,",
        "    .in_inv_std       = g_ninapro_in_inv_std,",
        "    .in_quant_scale   = NINAPRO_IN_QUANT_SCALE,",
        "    .conv1_weights    = g_ninapro_conv1_weights,",
        "    .conv1_bias       = g_ninapro_conv1_bias,",
        "    .conv1_eff_scale  = NINAPRO_CONV1_EFF_SCALE,",
        "    .conv2_weights    = g_ninapro_conv2_weights,",
        "    .conv2_bias       = g_ninapro_conv2_bias,",
        "    .conv2_eff_scale  = NINAPRO_CONV2_EFF_SCALE,",
        "    .fc_weights       = g_ninapro_fc_weights,",
        "    .fc_bias          = g_ninapro_fc_bias,",
        "    .fc_eff_scale     = NINAPRO_FC_EFF_SCALE,",
        "    .num_aux_features = 60,",
        "    .aux_mean         = g_ninapro_aux_mean,",
        "    .aux_inv_std      = g_ninapro_aux_inv_std,",
        "    .aux_quant_scale  = NINAPRO_AUX_QUANT_SCALE,",
        "    .aux_fc_weights   = g_ninapro_aux_fc_weights,",
        "    .aux_fc_eff_scale = NINAPRO_AUX_EFF_SCALE",
        "};",
        "",
        "#endif /* CNN1D_WEIGHTS_INT8_H */",
        "",
    ]

    content = "\n".join(chunks)
    for out_p in out_headers:
        out_p.parent.mkdir(parents=True, exist_ok=True)
        out_p.write_text(content, encoding="utf-8")
        print(f"Exported C header to {out_p} ({len(content):,} bytes)")


def main() -> int:
    parser = argparse.ArgumentParser(description="Export INT8 CNN-1D weights to C header.")
    parser.add_argument(
        "--npz",
        type=Path,
        default=ROOT / "reports" / "cnn1d_qemu" / "cnn1d_model_artifacts.npz",
    )
    args = parser.parse_args()

    out_headers = [
        ROOT / "embedded" / "firmware" / "include" / "cnn1d_weights_int8.h",
        ROOT / "embedded" / "firmware" / "src" / "cnn1d_weights_int8.h",
    ]
    generate_c_header(args.npz, out_headers)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
